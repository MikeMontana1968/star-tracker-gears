# PlatformIO pre-build script: gzip web/index.html into include/ui_gz.h so
# the UI lives in the firmware image (not LittleFS: `pio run -t uploadfs`
# would erase the schedule and the night log). Rewrites the header only
# when the page changed, so an unchanged UI does not force a rebuild.
#   extra_scripts = pre:tools/embed_ui.py      (platformio.ini)
#   python tools/embed_ui.py                   (by hand, from firmware/)
import gzip
import os

try:
    Import("env")  # noqa: F821 -- provided by PlatformIO
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

src = os.path.join(ROOT, "web", "index.html")
dst = os.path.join(ROOT, "include", "ui_gz.h")

with open(src, "rb") as f:
    raw = f.read()
# mtime=0: identical input gives identical bytes
gz = gzip.compress(raw, compresslevel=9, mtime=0)

lines = [
    "// GENERATED by tools/embed_ui.py from web/index.html -- do not edit",
    "#pragma once",
    "#include <stdint.h>",
    "#include <stddef.h>",
    "static const size_t UI_GZ_LEN = %d;   // %d bytes before gzip" % (len(gz), len(raw)),
    "static const uint8_t UI_GZ[] = {",
]
for i in range(0, len(gz), 20):
    lines.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
lines.append("};")
text = "\n".join(lines) + "\n"

old = None
if os.path.exists(dst):
    with open(dst, "r") as f:
        old = f.read()
if old != text:
    with open(dst, "w", newline="\n") as f:
        f.write(text)
    print("embed_ui: web/index.html %d -> %d bytes gzipped" % (len(raw), len(gz)))
